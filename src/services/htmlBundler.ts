import { FileNode } from '../types';
import { generateFullCompilloReplicaHtml } from './replicaHtmlGenerator';

export { generateFullCompilloReplicaHtml };

/**
 * Recursively retrieves all files from a FileNode tree.
 */
export function flattenFileTree(nodes: FileNode[]): FileNode[] {
  const result: FileNode[] = [];
  for (const node of nodes) {
    if (node.type === 'file') {
      result.push(node);
    } else if (node.children && node.children.length > 0) {
      result.push(...flattenFileTree(node.children));
    }
  }
  return result;
}

/**
 * Bundles HTML, CSS, and JS files from the workspace into a single self-contained HTML page.
 * All external <link rel="stylesheet"> references to local workspace files are replaced by inline <style>.
 * All external <script src="..."> references to local workspace files are replaced by inline <script>.
 */
export function bundleWorkspaceToSingleHtml(
  files: FileNode[],
  activeFile?: FileNode | null
): string {
  const allFiles = flattenFileTree(files);

  // 1. Identify base HTML file
  let htmlFile = activeFile && (activeFile.name.endsWith('.html') || activeFile.name.endsWith('.htm'))
    ? activeFile
    : allFiles.find((f) => f.name.toLowerCase() === 'index.html' || f.name.toLowerCase() === 'app.html') ||
      allFiles.find((f) => f.name.endsWith('.html') || f.name.endsWith('.htm'));

  let rawHtml = htmlFile?.content?.trim() || '';

  // If active file has HTML-like tags, treat it as HTML
  if (!rawHtml && activeFile?.content && (
    activeFile.content.includes('<html') ||
    activeFile.content.includes('<!DOCTYPE') ||
    activeFile.content.includes('<body') ||
    activeFile.content.includes('<div')
  )) {
    rawHtml = activeFile.content.trim();
  }

  // Fallback: If no HTML file is present, create a clean modern HTML5 container
  if (!rawHtml) {
    const title = activeFile?.name || 'Compillo Web App';
    rawHtml = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${title}</title>
</head>
<body>
  <div id="app">
    <h1>${title}</h1>
    <p>Single-page bundle generated by Compillo Studio.</p>
  </div>
</body>
</html>`;
  }

  // Ensure full HTML structure if only fragment was provided
  if (!rawHtml.toLowerCase().includes('<html')) {
    rawHtml = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Preview</title>
</head>
<body>
${rawHtml}
</body>
</html>`;
  }

  // Map of workspace files by clean filename and basename
  const cssFiles = allFiles.filter((f) => f.name.endsWith('.css') || f.name.endsWith('.scss'));
  const jsFiles = allFiles.filter((f) => f.name.endsWith('.js') || f.name.endsWith('.ts') || f.name.endsWith('.mjs'));

  const fileMap = new Map<string, string>();
  for (const f of allFiles) {
    fileMap.set(f.name.toLowerCase(), f.content || '');
    fileMap.set(f.path.toLowerCase(), f.content || '');
    fileMap.set(f.path.replace(/^\//, '').toLowerCase(), f.content || '');
  }

  let finalHtml = rawHtml;

  // 2. Inline linked stylesheets: <link rel="stylesheet" href="...">
  const linkedCssSet = new Set<string>();
  const linkRegex = /<link\b[^>]*rel=["']stylesheet["'][^>]*href=["']([^"']+)["'][^>]*\/?>|<link\b[^>]*href=["']([^"']+)["'][^>]*rel=["']stylesheet["'][^>]*\/?>/gi;

  finalHtml = finalHtml.replace(linkRegex, (match, href1, href2) => {
    const href = (href1 || href2 || '').trim();
    const cleanHref = href.replace(/^\.?\//, '').toLowerCase();
    const cssContent = fileMap.get(cleanHref) || fileMap.get(cleanHref.split('/').pop() || '');

    if (cssContent !== undefined) {
      linkedCssSet.add(cleanHref);
      return `<style data-bundle-source="${href}">\n${cssContent}\n</style>`;
    }
    // Keep external CDN links (e.g. Google Fonts)
    return match;
  });

  // Collect unlinked CSS files and inject them into <head>
  const unlinkedCss = cssFiles.filter((f) => {
    const cleanName = f.name.toLowerCase();
    const cleanPath = f.path.replace(/^\//, '').toLowerCase();
    return !linkedCssSet.has(cleanName) && !linkedCssSet.has(cleanPath);
  });

  if (unlinkedCss.length > 0) {
    const additionalStyles = unlinkedCss
      .map((f) => `<style data-source="${f.name}">\n/* === File: ${f.name} === */\n${f.content || ''}\n</style>`)
      .join('\n');

    if (finalHtml.includes('</head>')) {
      finalHtml = finalHtml.replace('</head>', `${additionalStyles}\n</head>`);
    } else {
      finalHtml = `${additionalStyles}\n${finalHtml}`;
    }
  }

  // 3. Inline script tags: <script src="..."></script>
  const linkedJsSet = new Set<string>();
  const scriptRegex = /<script\b[^>]*src=["']([^"']+)["'][^>]*>\s*<\/script>/gi;

  finalHtml = finalHtml.replace(scriptRegex, (match, src) => {
    const cleanSrc = (src || '').trim().replace(/^\.?\//, '').toLowerCase();
    const jsContent = fileMap.get(cleanSrc) || fileMap.get(cleanSrc.split('/').pop() || '');

    if (jsContent !== undefined) {
      linkedJsSet.add(cleanSrc);
      return `<script data-bundle-source="${src}">\n// <![CDATA[\n${jsContent}\n// ]]>\n</script>`;
    }
    // Keep external CDN scripts
    return match;
  });

  // Collect unlinked JS files (if active file wasn't JS or if there are other scripts)
  const unlinkedJs = jsFiles.filter((f) => {
    const cleanName = f.name.toLowerCase();
    const cleanPath = f.path.replace(/^\//, '').toLowerCase();
    return (
      !linkedJsSet.has(cleanName) &&
      !linkedJsSet.has(cleanPath) &&
      !f.name.endsWith('.config.js') &&
      !f.name.endsWith('.config.ts')
    );
  });

  if (unlinkedJs.length > 0) {
    const additionalScripts = unlinkedJs
      .map((f) => `<script data-source="${f.name}">\n// <![CDATA[\n/* === File: ${f.name} === */\n${f.content || ''}\n// ]]>\n</script>`)
      .join('\n');

    if (finalHtml.includes('</body>')) {
      finalHtml = finalHtml.replace('</body>', `${additionalScripts}\n</body>`);
    } else {
      finalHtml = `${finalHtml}\n${additionalScripts}`;
    }
  }

  return finalHtml;
}

/**
 * Triggers a download of the single-page HTML file in the user's browser.
 */
export function downloadSingleHtmlFile(htmlContent: string, fileName: string = 'single_page.html') {
  const blob = new Blob([htmlContent], { type: 'text/html;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = fileName.endsWith('.html') || fileName.endsWith('.htm') ? fileName : `${fileName}.html`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Generates a standalone, fully-featured single HTML page containing
 * HTML structure, CSS stylesheet, and JavaScript logic for Compillo Studio.
 * Runs independently in any browser without build tools or external servers.
 */
export function generateSelfContainedStudioHtml(): string {
  return generateFullCompilloReplicaHtml();
}
